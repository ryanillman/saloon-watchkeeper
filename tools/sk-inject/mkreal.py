#!/usr/bin/env python3
"""Makes real-electrical.json: the Signal K deltas a real NMEA 2000 server would have produced from a captured bus.

  mkreal.py [--capture tests/fixtures/electrical/capture.candump] [--devices real-electrical-devices.json]
            [--out real-electrical.json]

Reads a `candump -L` log (PGNs 127508 battery status, 127506 DC detailed status, 127750 converter status,
127744 AC input), keeps the last value of every leaf per sending device, and writes one update per
(device, PGN) with a source object the server turns into "$source": "can0.<address>". Device identity from the
devices file goes on the source object, which the server files under sources.can0.<address>.n2k (canName,
modelId...), as it does for a real device. The point is to keep what a plain tree loses: several devices
reporting the same path (instance 0 from the shunt, both solar controllers and the charger), and a solar panel's
input published as battery instance 1.
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LINE = re.compile(r"\(\S+\)\s+\S+\s+([0-9A-Fa-f]+)#([0-9A-Fa-f]*)")
# canboat's converter operating states, as the Signal K server publishes them (lower case)
STATES = {0: "off", 1: "low power mode", 2: "fault", 3: "bulk", 4: "absorption", 5: "float", 6: "storage",
          7: "equalize", 8: "pass-thru", 9: "inverting", 10: "assisting"}
FAST = {127506}
NO_ESTIMATE_MIN = 14399


def _u16(d, i):
    return d[i] | d[i + 1] << 8


def _i16(d, i):
    v = _u16(d, i)
    return v - 0x10000 if v >= 0x8000 else v


def _pgn(can_id):
    pf = (can_id >> 16) & 0xFF
    return (can_id >> 8) & 0x1FFFF if pf >= 240 else (can_id >> 8) & 0x1FF00


def _decode(pgn, src, d):
    """{path: value} for one reassembled message; a field that is not available is left out."""
    out = {}
    if pgn == 127508 and len(d) >= 5:
        base = f"electrical.batteries.{d[0]}"
        if _u16(d, 1) < 0xFFFE:
            out[f"{base}.voltage"] = round(_u16(d, 1) * 0.01, 2)
        if _i16(d, 3) < 0x7FFE:
            out[f"{base}.current"] = round(_i16(d, 3) * 0.1, 1)
        if len(d) >= 7 and _u16(d, 5) < 0xFFFE:
            out[f"{base}.temperature"] = round(_u16(d, 5) * 0.01, 2)
    elif pgn == 127506 and len(d) >= 4:
        base = f"electrical.batteries.{d[1]}"
        if d[3] <= 100:
            out[f"{base}.capacity.stateOfCharge"] = round(d[3] / 100, 2)
        if len(d) >= 7 and _u16(d, 5) < 0xFFFE:
            minutes = _u16(d, 5)
            # 240 h (14399 min) is the sender's "no estimate" cap; the server published it as null
            out[f"{base}.capacity.timeRemaining"] = None if minutes >= NO_ESTIMATE_MIN else minutes * 60
    elif pgn == 127750 and len(d) >= 3 and d[2] in STATES:
        out[f"electrical.converter.{src}.{d[1]}.operatingState"] = STATES[d[2]]
    elif pgn == 127744 and len(d) >= 4 and _u16(d, 2) < 0xFFFE:
        out[f"electrical.ac.{src}.{d[1]}.phase.A.current"] = round(_u16(d, 2) * 0.1, 1)
    return out


def decode_frames(lines):
    """{(source address, pgn): {path: last value}} from candump -L lines."""
    leaves, partial = {}, {}
    for line in lines:
        m = LINE.match(line.strip())
        if not m:
            continue
        can_id, data = int(m[1], 16), bytes.fromhex(m[2])
        pgn, src = _pgn(can_id), str(can_id & 0xFF)
        if pgn not in (127508, 127506, 127750, 127744) or not data:
            continue
        if pgn in FAST:
            if data[0] & 0x1F == 0:   # first frame: byte 1 is the total length
                partial[(src, pgn)] = [data[1], bytearray(data[2:])]
            elif (src, pgn) in partial:
                partial[(src, pgn)][1].extend(data[1:])
            total, buf = partial.get((src, pgn), [0, b""])
            if not total or len(buf) < total:
                continue
            data = bytes(buf[:total])
            del partial[(src, pgn)]
        leaves.setdefault((src, pgn), {}).update(_decode(pgn, src, data))
    return {k: v for k, v in leaves.items() if v}


def build(capture_text, devices):
    leaves = decode_frames(capture_text.splitlines())
    updates = []
    for (src, pgn), values in sorted(leaves.items(), key=lambda kv: (int(kv[0][0]), kv[0][1])):
        source = {"label": devices["label"], "type": "NMEA2000", "src": src, "pgn": pgn}
        source.update(devices["devices"].get(src, {}))
        updates.append({"source": source, "values": [{"path": p, "value": values[p]} for p in sorted(values)]})
    return {
        "description": "Generated by mkreal.py from tests/fixtures/electrical/capture.candump. One update per (device, PGN), "
                       "as a real NMEA 2000 server would publish the bus. Do not edit by hand.",
        "updates": updates,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--capture", default=str(HERE.parents[1] / "tests/fixtures/electrical/capture.candump"))
    ap.add_argument("--devices", default=str(HERE / "real-electrical-devices.json"))
    ap.add_argument("--out", default=str(HERE / "real-electrical.json"))
    args = ap.parse_args()
    doc = build(Path(args.capture).read_text(), json.loads(Path(args.devices).read_text()))
    Path(args.out).write_text(json.dumps(doc, indent=1) + "\n")
    n = sum(len(u["values"]) for u in doc["updates"])
    print(f"wrote {args.out}: {len(doc['updates'])} updates, {n} values", file=sys.stderr)


if __name__ == "__main__":
    main()
